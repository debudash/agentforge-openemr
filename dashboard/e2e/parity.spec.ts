// The parity harness (spec section 7): for every patient on the dev stack, the legacy dashboard
// (through the tabs shell, as doctor1) and the new one (through SMART login, as doctor1) are
// rendered, their cards extracted and compared. The run fails on any unexplained difference.
// The report is written to .scratch/dashboard-modernization/04-evidence/parity/.
import { test, expect, type Browser } from "@playwright/test";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { stackPatients, type StackPatient } from "./support/env";
import { signInToLegacy, openLegacyPatient, extractLegacy } from "./support/legacy";
import { signInToDashboard } from "./support/smart";
import { extractPort } from "./support/port";
import { comparePatient, type CardResult } from "./support/compare";

const REPORT_DIR = fileURLToPath(new URL("../../.scratch/dashboard-modernization/04-evidence/parity/", import.meta.url));
const only = process.env.PARITY_PIDS?.split(",").map(Number);
const patients: StackPatient[] = stackPatients().filter((p) => !only || only.includes(p.pid));
type PatientResult = { pid: number; cards: CardResult[] };
// Each patient's result is written as it finishes: a failed test restarts the worker, which
// would lose results held in memory. The report is built from these files.
const PID_DIR = `${REPORT_DIR}pids/`;

async function legacyPage(browser: Browser) {
  const ctx = await browser.newContext({ ignoreHTTPSErrors: true });
  const page = await ctx.newPage();
  await signInToLegacy(page);
  return page;
}

let legacy: Awaited<ReturnType<typeof legacyPage>> | undefined;

test.beforeAll(async ({ browser }) => {
  legacy = await legacyPage(browser);
});

for (const patient of patients) {
  test(`parity pid ${String(patient.pid)}`, async ({ page }) => {
    if (!legacy) throw new Error("legacy session missing");
    let frame;
    try {
      frame = await openLegacyPatient(legacy, patient.pid);
    } catch {
      // The legacy session can expire during a long run: sign in again once.
      await signInToLegacy(legacy);
      frame = await openLegacyPatient(legacy, patient.pid);
    }
    const legacyCards = await extractLegacy(legacy, frame);
    await signInToDashboard(page, patient.uuid);
    const portCards = await extractPort(page);
    const cards = comparePatient(patient.pid, legacyCards, portCards);
    mkdirSync(PID_DIR, { recursive: true });
    writeFileSync(`${PID_DIR}${String(patient.pid)}.json`, JSON.stringify({ pid: patient.pid, cards } satisfies PatientResult, null, 2) + "\n");
    const unexplained = cards.flatMap((c) => c.differences.filter((d) => d.rule === null).map((d) => `${c.card}: ${d.what}`));
    expect(unexplained, `unexplained differences for pid ${String(patient.pid)}`).toEqual([]);
  });
}

test.afterAll(() => {
  mkdirSync(PID_DIR, { recursive: true });
  const results: PatientResult[] = readdirSync(PID_DIR)
    .filter((f) => f.endsWith(".json"))
    .map((f) => JSON.parse(readFileSync(`${PID_DIR}${f}`, "utf8")) as PatientResult)
    .sort((a, b) => a.pid - b.pid);
  writeFileSync(`${REPORT_DIR}parity-report.json`, JSON.stringify(results, null, 2) + "\n");
  writeFileSync(`${REPORT_DIR}parity-report.md`, renderMarkdown(results));
});

function renderMarkdown(rs: readonly PatientResult[]): string {
  const cards = ["header", "allergies", "problems", "medications", "prescriptions", "care-team", "vitals"];
  const lines = [
    "# Parity harness report",
    "",
    `Run ${new Date().toISOString()} against the local dev stack: ${String(rs.length)} patients, legacy dashboard (tabs shell, doctor1) vs the new dashboard (SMART login, doctor1). Generated by \`dashboard/e2e/parity.spec.ts\`; raw data in \`parity-report.json\`.`,
    "",
    "## Summary per card",
    "",
    "| Card | Match | Explained | Flagged | Unexplained | Items legacy / port |",
    "|---|---|---|---|---|---|",
  ];
  for (const c of cards) {
    const rows = rs.map((r) => r.cards.find((x) => x.card === c)).filter((x): x is CardResult => x !== undefined);
    const n = (v: string) => String(rows.filter((r) => r.verdict === v).length);
    const items = `${String(rows.reduce((s, r) => s + r.legacy.length, 0))} / ${String(rows.reduce((s, r) => s + r.port.length, 0))}`;
    lines.push(`| ${c} | ${n("match")} | ${n("explained")} | ${n("flagged")} | ${n("unexplained")} | ${items} |`);
  }
  lines.push("", "## Differences by rule", "", "| Card | Rule | Occurrences | Patients |", "|---|---|---|---|");
  const byRule = new Map<string, { card: string; rule: string; count: number; pids: Set<number> }>();
  for (const r of rs) {
    for (const c of r.cards) {
      for (const d of c.differences) {
        const rule = d.rule ?? "UNEXPLAINED";
        const key = `${c.card}|${rule}`;
        const e = byRule.get(key) ?? { card: c.card, rule, count: 0, pids: new Set<number>() };
        e.count += 1;
        e.pids.add(r.pid);
        byRule.set(key, e);
      }
    }
  }
  for (const e of [...byRule.values()].sort((a, b) => a.card.localeCompare(b.card) || b.count - a.count)) {
    lines.push(`| ${e.card} | ${e.rule.replace(/\|/g, "\\|")} | ${String(e.count)} | ${String(e.pids.size)} |`);
  }
  const unexplained = rs.flatMap((r) => r.cards.flatMap((c) => c.differences.filter((d) => d.rule === null).map((d) => `- pid ${String(r.pid)}, ${c.card}: ${d.what}`)));
  lines.push("", "## Unexplained differences", "", ...(unexplained.length ? unexplained : ["None."]), "");
  return lines.join("\n");
}
